"""Client of the cymon trace protocol (cymon-lib on the node)."""

from __future__ import annotations

import asyncio
import dataclasses
import logging
from typing import Any

import cymon as cymon_dsdl  # DSDL namespace generated by dsdl.setup(), not this package
import pycyphal.application

from .events import EventHub
from .registers import RegisterClient, RegisterError

_logger = logging.getLogger(__name__)

#: Service types of the protocol, by the key used in this module.
SERVICES = {
    "variables": "cymon.GetVariableList.0.1",
    "buffer_info": "cymon.GetBufferInfo.0.1",
    "setup": "cymon.SetupCapture.0.1",
    "arm": "cymon.ArmTrigger.0.1",
    "read": "cymon.ReadSamples.0.1",
}

TRIGGER_MODES = {"rising": 0, "falling": 1, "hysteresis": 2, "immediate": 3}
STATES = {0: "idle", 1: "configured", 2: "armed", 3: "triggered", 4: "complete"}
ERRORS = {
    0: "none",
    1: "bad channel id",
    2: "buffer too small",
    3: "not configured",
    5: "already capturing",
    9: "bad config",
}


class ScopeError(Exception):
    pass


@dataclasses.dataclass
class CaptureRequest:
    channels: list[int]
    sample_period_us: float
    num_samples: int
    pretrigger_samples: int = 0
    trigger_mode: str = "immediate"
    trigger_source: int = 0
    trigger_level: float = 0.0
    hysteresis_band: float = 0.0
    timeout_s: float = 30.0


class ScopeClient:
    """Finds the cymon services of nodes and runs captures on them."""

    def __init__(self, node: pycyphal.application.Node, registers: RegisterClient, events: EventHub) -> None:
        self._node = node
        self._registers = registers
        self._events = events
        self._service_ids: dict[int, dict[str, int]] = {}
        self._clients: dict[tuple[int, str], Any] = {}
        self._jobs: dict[int, asyncio.Task[dict[str, Any]]] = {}

    async def discover(self, node_id: int, refresh: bool = False) -> dict[str, int]:
        """Service-IDs of the cymon services from the ``uavcan.srv.*.type`` registers (empty: no cymon)."""
        if refresh or node_id not in self._service_ids:
            try:
                ports = await self._registers.port_map(node_id)
            except RegisterError as ex:
                raise ScopeError(f"Cannot read the port registers of node {node_id}: {ex}") from ex
            by_type = {p["type"]: p["id"] for p in ports if p["direction"] == "srv" and p["id"] is not None}
            found = {key: by_type[t] for key, t in SERVICES.items() if t in by_type}
            for key in [k for k in self._clients if k[0] == node_id]:
                self._clients.pop(key).close()
            self._service_ids[node_id] = found
        return self._service_ids[node_id]

    def forget(self, node_id: int) -> None:
        self._service_ids.pop(node_id, None)
        for key in [k for k in self._clients if k[0] == node_id]:
            self._clients.pop(key).close()

    async def _call(self, node_id: int, key: str, request: Any, timeout: float = 0.5, attempts: int = 3) -> Any:
        ids = await self.discover(node_id)
        missing = [k for k in SERVICES if k not in ids]
        if missing:
            raise ScopeError(f"Node {node_id} has no cymon services ({', '.join(missing)} missing)")
        if (node_id, key) not in self._clients:
            dtype = getattr(cymon_dsdl, SERVICES[key].split(".")[1] + "_0_1")
            client = self._node.presentation.make_client(dtype, ids[key], node_id)
            self._clients[(node_id, key)] = client
        client = self._clients[(node_id, key)]
        client.response_timeout = timeout
        for _ in range(attempts):
            result = await client.call(request)
            if result is not None:
                return result[0]
        raise ScopeError(f"Node {node_id} did not answer {SERVICES[key]}")

    async def info(self, node_id: int) -> dict[str, Any]:
        variables = []
        for index in range(256):
            resp = await self._call(node_id, "variables", cymon_dsdl.GetVariableList_0_1.Request(index=index))
            name = resp.name.tobytes().decode("utf8", errors="replace")
            if not name:
                break
            variables.append({"id": index, "name": name, "unit": resp.unit.tobytes().decode("utf8", errors="replace")})
        buf = await self._call(node_id, "buffer_info", cymon_dsdl.GetBufferInfo_0_1.Request())
        return {
            "node_id": node_id,
            "services": await self.discover(node_id),
            "variables": variables,
            "buffer": {
                "buffer_bytes": int(buf.buffer_bytes),
                "max_channels": int(buf.max_channels),
                "max_frames": int(buf.max_frames),
                "max_read_samples": int(buf.max_read_samples),
                "tick_period_us": float(buf.tick_period_us),
            },
        }

    async def status(self, node_id: int) -> dict[str, Any]:
        resp = await self._call(node_id, "read", cymon_dsdl.ReadSamples_0_1.Request(frame_offset=0, max_frames=0))
        return {
            "state": STATES.get(int(resp.state.value), str(resp.state.value)),
            "num_channels": int(resp.num_channels),
            "num_samples": int(resp.num_samples),
            "pretrigger_samples": int(resp.pretrigger_samples),
            "sample_period_us": float(resp.sample_period_us),
        }

    async def disarm(self, node_id: int) -> None:
        await self._call(node_id, "arm", cymon_dsdl.ArmTrigger_0_1.Request(arm=False))

    async def capture(self, node_id: int, request: CaptureRequest) -> dict[str, Any]:
        """Setup, arm, wait for completion, read out. Emits ``capture`` progress events."""
        if request.trigger_mode not in TRIGGER_MODES:
            raise ScopeError(f"Unknown trigger mode {request.trigger_mode!r}")
        setup = await self._call(
            node_id,
            "setup",
            cymon_dsdl.SetupCapture_0_1.Request(
                channel_ids=request.channels,
                sample_period_us=request.sample_period_us,
                num_samples=request.num_samples,
                pretrigger_samples=request.pretrigger_samples,
            ),
        )
        self._check(setup.result.value, "SetupCapture")
        arm = await self._call(
            node_id,
            "arm",
            cymon_dsdl.ArmTrigger_0_1.Request(
                arm=True,
                source_variable_id=request.trigger_source,
                mode=cymon_dsdl.TriggerMode_0_1(TRIGGER_MODES[request.trigger_mode]),
                level=request.trigger_level,
                hysteresis_band=request.hysteresis_band,
            ),
        )
        self._check(arm.result.value, "ArmTrigger")
        self._events.emit("capture", node_id=node_id, state="armed", period_us=float(setup.actual_sample_period_us))

        loop = asyncio.get_running_loop()
        deadline = loop.time() + request.timeout_s
        state = "armed"
        while state != "complete":
            if loop.time() > deadline:
                await self.disarm(node_id)
                raise ScopeError(f"Capture on node {node_id} did not complete within {request.timeout_s} s ({state})")
            await asyncio.sleep(0.05)
            new_state = (await self.status(node_id))["state"]
            if new_state != state:
                state = new_state
                self._events.emit("capture", node_id=node_id, state=state)
            if state in ("idle", "configured"):
                raise ScopeError(f"Capture on node {node_id} was disarmed")

        return await self.read(node_id)

    async def read(self, node_id: int) -> dict[str, Any]:
        """Reads a complete capture; ``t`` is relative to the trigger sample [s]."""
        frames: list[list[float]] = []
        offset = 0
        meta: Any = None
        while True:
            resp = await self._call(
                node_id, "read", cymon_dsdl.ReadSamples_0_1.Request(frame_offset=offset, max_frames=255)
            )
            meta = resp
            if int(resp.state.value) != 4:
                raise ScopeError(f"Capture on node {node_id} is not complete")
            n = int(resp.num_channels)
            values = [float(v) for v in resp.samples]
            frames += [values[i : i + n] for i in range(0, len(values) - n + 1, n)]
            offset = len(frames)
            if resp.end_of_data or not values:
                break
        period = float(meta.sample_period_us) * 1e-6
        pre = int(meta.pretrigger_samples)
        result = {
            "node_id": node_id,
            "sample_period_us": float(meta.sample_period_us),
            "pretrigger_samples": pre,
            "t": [(i - pre) * period for i in range(len(frames))],
            "channels": [[f[c] for f in frames] for c in range(int(meta.num_channels))],
        }
        self._events.emit("capture", node_id=node_id, state="read", frames=len(frames))
        return result

    @staticmethod
    def _check(code: int, what: str) -> None:
        if int(code) != 0:
            raise ScopeError(f"{what} refused: {ERRORS.get(int(code), code)}")
